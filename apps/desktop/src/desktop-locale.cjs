function normalizePreference(value) {
  if (typeof value !== 'string') return undefined
  const normalized = value.trim().toLowerCase()
  return SUPPORTED_LOCALES.has(normalized) ? normalized : undefined
}

function localeFromSystem(value) {
  if (typeof value !== 'string') return 'en'
  return /^zh(?:[-_]|$)/i.test(value.trim()) ? 'zh' : 'en'
}

function normalizeLocale(value, systemLocale = 'en') {
  return normalizePreference(value) || localeFromSystem(systemLocale)
}

function getLocaleMessages(locale) {
  return MESSAGES[normalizePreference(locale) || 'en']
}

function formatMessage(template, values = {}) {
  if (typeof template !== 'string') return ''
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (_match, key) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : `{${key}}`
  ))
}

function messageForLocale(locale, key, values = {}) {
  const value = key.split('.').reduce((current, part) => current && current[part], getLocaleMessages(locale))
  return formatMessage(value, values)
}

